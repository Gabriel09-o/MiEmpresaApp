public class App {
    public static void sumar (double a, double b) {
        return a + b;
}
    public static void restar (double a, double b) {
        return a - b;
    }
    public static void multiplicar (double a, double b) {
        return a * b;
    }
    public static void dividir (double a, double b) {
        return a / b;
    }
}